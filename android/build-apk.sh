#!/bin/bash
# 构建 竞彩预测 Android APK（无需 Gradle）。用法：
#   API_BASE=http://你的服务器:8088 ./android/build-apk.sh
# 环境变量：
#   API_BASE       APP 固定使用的服务器地址（写入 www/config.js，APP 内不可修改；默认 http://120.77.152.74:8088）
#   JAVA_HOME      JDK 17（默认 /opt/android-tools/jdk17）
#   ANDROID_HOME   Android SDK（默认 /opt/android-tools/sdk，需 platforms;android-34 与 build-tools;34.0.0）
#   KEYSTORE / KS_PASS / KEY_ALIAS   签名密钥（默认 android/release.keystore，首次自动生成自签名密钥）
#   VERSION_NAME / VERSION_CODE      版本号（默认见脚本内；与 VERSION.txt 同步）
# 生产同步勿覆盖服务器 .env：见 docs/deploy-aliyun.md、tools/sync-prod.sh
#   OUT            输出路径（默认 dist/jingcai-predict.apk）
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; A="$ROOT/android"
export JAVA_HOME="${JAVA_HOME:-/opt/android-tools/jdk17}"; export PATH="$JAVA_HOME/bin:$PATH"
SDK="${ANDROID_HOME:-/opt/android-tools/sdk}"; BT="$SDK/build-tools/34.0.0"; JAR="$SDK/platforms/android-34/android.jar"
KEYSTORE="${KEYSTORE:-$A/release.keystore}"; KS_PASS="${KS_PASS:-jingcai-predict}"; KEY_ALIAS="${KEY_ALIAS:-jingcai}"
VERSION_NAME="${VERSION_NAME:-1.9.238}"; VERSION_CODE="${VERSION_CODE:-275}"
API_BASE="${API_BASE:-http://120.77.152.74:8088}"; API_BASE="${API_BASE%/}"
case "$API_BASE" in http://*|https://*) ;; *) echo "API_BASE must start with http:// or https://" >&2; exit 1;; esac
OUT="${OUT:-$ROOT/dist/jingcai-predict.apk}"; B="$A/build"
rm -rf "$B"; mkdir -p "$B/assets/www" "$B/gen" "$B/classes" "$B/res" "$ROOT/dist"

# 1) bundle frontend (sw.js not needed inside the app) + build-time config
cp -r "$ROOT/public/." "$B/assets/www/"; rm -f "$B/assets/www/sw.js" "$B/assets/www/"*.apk
for _req in \
  "$B/assets/www/banners/slide-hot-match.jpg" \
  "$B/assets/www/banners/slide-news.jpg" \
  "$B/assets/www/banners/slide-contra.jpg" \
  "$B/assets/www/demos/assets/soccer_ball.glb"; do
  if [ ! -f "$_req" ]; then echo "Missing required APK asset: $_req" >&2; exit 1; fi
done
CHANNEL="${CHANNEL:-prod}"
PARTNER_KEY="${PARTNER_BUILD_KEY:-}"
BUILD_ID="${BUILD_ID:-$(date +%Y%m%d-%H%M)}"
if [ "$CHANNEL" = "partner-test" ] && [ -z "$PARTNER_KEY" ]; then
  echo "PARTNER_BUILD_KEY required for CHANNEL=partner-test" >&2; exit 1
fi
node -e '
const [b,v,ch,pk,bid]=process.argv.slice(1);
const cfg={apiBase:b,platform:"android",version:v,channel:ch||"prod",buildId:bid||""};
if(ch==="partner-test"){cfg.partnerKey=pk;cfg.channel="partner-test";}
process.stdout.write("// generated by android/build-apk.sh\nwindow.APP_CONFIG = "+JSON.stringify(cfg)+";\n");
' "$API_BASE" "$VERSION_NAME" "$CHANNEL" "$PARTNER_KEY" "$BUILD_ID" > "$B/assets/www/config.js"
echo "API_BASE (fixed): ${API_BASE}  version ${VERSION_NAME} (${VERSION_CODE}) channel=${CHANNEL} buildId=${BUILD_ID}"

# 2) resources + manifest
sed -e "s/android:versionCode=\"[0-9]*\"/android:versionCode=\"$VERSION_CODE\"/" -e "s/android:versionName=\"[^\"]*\"/android:versionName=\"$VERSION_NAME\"/" "$A/AndroidManifest.xml" > "$B/AndroidManifest.xml"
if [ "$CHANNEL" = "partner-test" ]; then
  # Anti-leak basics: disable backup of WebView/local data
  sed -i 's/android:allowBackup="true"/android:allowBackup="false"/' "$B/AndroidManifest.xml" || true
fi
"$BT/aapt2" compile --dir "$A/res" -o "$B/res/res.zip"
"$BT/aapt2" link -o "$B/unsigned.apk" -I "$JAR" --manifest "$B/AndroidManifest.xml" -A "$B/assets" --java "$B/gen" --min-sdk-version 24 --target-sdk-version 34 "$B/res/res.zip"

# 3) compile java -> dex
mkdir -p "$B/gen/com/tiicai/jingcai"
printf 'package com.tiicai.jingcai;\nfinal class BuildConfigVersion { static final String NAME = "%s"; static final int CODE = %s; }\n' "$VERSION_NAME" "$VERSION_CODE" > "$B/gen/com/tiicai/jingcai/BuildConfigVersion.java"
javac --release 11 -classpath "$JAR" -d "$B/classes" $(find "$A/src" "$B/gen" -name '*.java')
"$BT/d8" --release --min-api 24 --lib "$JAR" --output "$B" $(find "$B/classes" -name '*.class')
(cd "$B" && zip -qj unsigned.apk classes.dex)

# 4) align + sign (self-signed release key; keep the keystore to publish updates over installed versions)
if [ ! -f "$KEYSTORE" ]; then
  keytool -genkeypair -keystore "$KEYSTORE" -storepass "$KS_PASS" -keypass "$KS_PASS" -alias "$KEY_ALIAS" \
    -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=Jingcai Predict, OU=App, O=tiicai-site, C=CN"
fi
"$BT/zipalign" -f -p 4 "$B/unsigned.apk" "$B/aligned.apk"
"$BT/apksigner" sign --ks "$KEYSTORE" --ks-pass "pass:$KS_PASS" --key-pass "pass:$KS_PASS" --ks-key-alias "$KEY_ALIAS" --v4-signing-enabled false --out "$OUT" "$B/aligned.apk"
"$BT/apksigner" verify --verbose "$OUT" | head -6
ls -l "$OUT"
